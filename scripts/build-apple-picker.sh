#!/usr/bin/env bash
#
# Build Apple Picker to WebGL and drop it in public/demos/apple-picker/.
#
# The game lives in its own Unity project outside this repo; only the build
# output is committed here, which is what lets the site serve a playable Unity
# game as plain static files: no Unity hosting, no account, nothing to keep
# alive. The build itself is driven by PortfolioWebGLBuild.cs inside that
# project, so the settings that matter (no compression, minimal template,
# high stripping) are in version control rather than in someone's Build
# Settings window.
#
# Requirements: the Unity editor the project was made with, *with the WebGL
# Build Support module*. A stock install has only the standalone one, and
# without webgl this fails with "Unable to find a build target".
#
#   ./scripts/build-apple-picker.sh
#
# Takes several minutes: the first WebGL build compiles the whole engine
# through IL2CPP and Emscripten.

set -euo pipefail

PROJECT="${APPLE_PICKER_PROJECT:-$HOME/Unity Projects/Apple Picker}"
UNITY="${UNITY_BIN:-/Applications/Unity/Unity-6000.5.11f1/Unity.app/Contents/MacOS/Unity}"
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$REPO/public/demos/apple-picker"
LOG="${TMPDIR:-/tmp}/apple-picker-webgl.log"

[ -d "$PROJECT" ] || { echo "No Unity project at: $PROJECT" >&2; exit 1; }
[ -x "$UNITY" ]   || { echo "No Unity editor at: $UNITY" >&2; exit 1; }

# PlaybackEngines sits beside Unity.app, not inside it: the editor binary is
# <root>/Unity.app/Contents/MacOS/Unity and the modules are <root>/PlaybackEngines.
EDITOR_ROOT="$(cd "$(dirname "$UNITY")/../../.." && pwd)"

if [ ! -d "$EDITOR_ROOT/PlaybackEngines/WebGLSupport" ]; then
  echo "This editor has no WebGL module. Install it with:" >&2
  echo "  '/Applications/Unity Hub.app/Contents/MacOS/Unity Hub' -- --headless \\" >&2
  echo "    install-modules --version 6000.5.11f1 -m webgl --childModules" >&2
  exit 1
fi

echo "Building $PROJECT -> $OUT"
echo "Log: $LOG"
rm -rf "$OUT"
mkdir -p "$OUT"

APPLE_PICKER_WEBGL_OUT="$OUT" "$UNITY" \
  -quit -batchmode -nographics \
  -projectPath "$PROJECT" \
  -executeMethod PortfolioWebGLBuild.Build \
  -buildTarget WebGL \
  -logFile "$LOG"

# Unity's Minimal template hardcodes a 960x600 canvas in px, which inside an
# iframe either overflows a narrow column or floats in a letterbox. We serve
# this in our own frame, so the page around the canvas is ours: it fills,
# matches the site's black, reports loading progress, and fails with readable
# text instead of a browser alert() fired from inside an iframe.
echo "Replacing Unity's index.html with the embeddable one"
cat > "$OUT/index.html" <<'HTML'
<!doctype html>
<!-- Generated by scripts/build-apple-picker.sh, so edit the script, not this. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Apple Picker</title>
    <style>
      html, body { height: 100%; margin: 0; background: #000; overflow: hidden; }
      #unity-canvas { display: block; width: 100%; height: 100%; background: #000; }
      #loading {
        position: absolute; inset: 0; display: flex; align-items: center;
        justify-content: center; color: rgba(255,255,255,0.55);
        font: 400 13px/1.6 ui-monospace, SFMono-Regular, Menlo, monospace;
        text-align: center; padding: 0 24px;
      }
    </style>
  </head>
  <body>
    <!-- The width/height attributes are the build's own resolution and are
         deliberately present: without them a canvas reports a 300x150
         drawing buffer at the moment the WebGL context is created, which is
         not what Unity's own template does. CSS still stretches it to fill
         the frame. -->
    <canvas id="unity-canvas" width="960" height="600" tabindex="-1"></canvas>
    <p id="loading">Loading…</p>
    <script src="Build/apple-picker.loader.js"></script>
    <script>
      // Not `status`: `window.status` is a legacy property whose setter
      // coerces to a string, so a top-level `var status = <element>` stores
      // "[object HTMLParagraphElement]" instead of the node. The progress
      // text then silently never updates and `.remove()` throws on a string,
      // leaving "Loading…" on top of a game that loaded fine.
      var statusEl = document.querySelector("#loading");
      var canvas = document.querySelector("#unity-canvas");

      function fail(reason) {
        if (!statusEl.isConnected) document.body.appendChild(statusEl);
        statusEl.innerHTML =
          reason +
          "<br><br>Chrome and Firefox run it fine, and the source is on GitHub.";
      }

      // Unity 6 emits WebGL 2 only. Checking first means a browser that
      // cannot run this at all gets a sentence instead of Unity's own dialog
      // and a wall of wasm stack trace.
      var probe = document.createElement("canvas");
      var supported = false;
      try {
        supported = !!(window.WebGL2RenderingContext && probe.getContext("webgl2"));
      } catch (e) {
        supported = false;
      }

      // Safari drops the context on some machines mid-startup (WebKit
      // 286297). Emscripten's glue then dereferences a null shader and
      // throws something unreadable, so say what actually happened.
      canvas.addEventListener("webglcontextlost", function (e) {
        e.preventDefault();
        fail("This browser dropped the WebGL context while the game was starting.");
      });

      if (!supported) {
        fail("This browser does not support WebGL 2, which this build needs.");
      } else {
      createUnityInstance(canvas, {
        dataUrl: "Build/apple-picker.data.unityweb",
        frameworkUrl: "Build/apple-picker.framework.js.unityweb",
        codeUrl: "Build/apple-picker.wasm.unityweb",
        streamingAssetsUrl: "StreamingAssets",
        companyName: "DefaultCompany",
        productName: "Apple Picker",
        productVersion: "0.1.0",
      }, function (progress) {
        statusEl.textContent = "Loading… " + Math.round(progress * 100) + "%";
      }).then(function () {
        statusEl.remove();
      }).catch(function (message) {
        fail(String(message));
      });
      }
    </script>
  </body>
</html>
HTML

echo
echo "Built. Payload:"
find "$OUT/Build" -type f -exec du -h {} \; 2>/dev/null | sort -h
echo
echo "Total: $(du -sh "$OUT" | cut -f1)"
